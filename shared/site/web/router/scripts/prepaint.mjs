// npm run build (after tsc): writes dist/prepaint.js, the site's pre-paint script
// (ADR-119 D17, P-91 to P-98). A classic, render-blocking script cannot import, so it
// carries what it needs: the palette build's offer (../palette/dist/themes.json) and
// the source text of the router's choice functions, copied from the compiled module
// (src/router.ts says which, and that they must stay self-contained). Deterministic:
// the same inputs give the same bytes.
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import * as router from "../dist/router.js"

const here = import.meta.dirname
const data = JSON.parse(readFileSync(path.join(here, "..", "..", "palette", "dist", "themes.json"), "utf8"))
const FUNCTIONS = ["storageKey", "readStored", "validAccent", "resolveChoice", "systemDark", "applyChoice", "prepaint"]

const source = FUNCTIONS.map((name) => {
  const f = router[name]
  if (typeof f !== "function") throw new Error(`dist/router.js exports no function ${name}`)
  return f.toString()
}).join("\n")

const out =
  "// SPDX-License-Identifier: GPL-3.0-or-later\n" +
  "// Generated by scripts/prepaint.mjs from src/router.ts and the palette's themes.json:\n" +
  "// do not edit. MAE's site pre-paint script (ADR-119 D17): a classic script in <head>\n" +
  "// that applies the reader's stored mode and palette before first paint.\n" +
  "(function () {\n" +
  '"use strict";\n' +
  `var data = ${JSON.stringify(data)};\n` +
  `${source}\n` +
  "try {\n" +
  "  prepaint(window, data);\n" +
  "} catch (_) {\n" +
  "  // Nothing applied: the stylesheets' own defaults hold (the system's mode).\n" +
  "}\n" +
  "})();\n"

writeFileSync(path.join(here, "..", "dist", "prepaint.js"), out)
console.log("dist/prepaint.js")
