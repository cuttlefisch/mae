const LEGIBLE = 3

// --- colour: OKLab and OKLCH, there and back ---------------------------------

const gamma = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055)

/** sRGB (0..1, unclipped) of an OKLab colour. */
function rgbOf([L, a, b]) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map(gamma)
}
const inside = (rgb) => rgb.every((c) => c >= -1e-4 && c <= 1 + 1e-4)
const hexOf = (rgb) =>
  `#${rgb.map((c) => Math.round(Math.min(1, Math.max(0, c)) * 255).toString(16).padStart(2, "0")).join("")}`

/** An OKLab colour to #rrggbb: if it falls outside sRGB, chroma is lowered (same hue and lightness). */
function hex(lab) {
  const [L, a, b] = [Math.min(1, Math.max(0, lab[0])), lab[1], lab[2]]
  if (inside(rgbOf([L, a, b]))) return hexOf(rgbOf([L, a, b]))
  let [lo, hi] = [0, 1]
  for (let k = 0; k < 30; k++) {
    const x = (lo + hi) / 2
    if (inside(rgbOf([L, a * x, b * x]))) lo = x
    else hi = x
  }
  return hexOf(rgbOf([L, a * lo, b * lo]))
}
const lch = (h) => {
  const [L, a, b] = oklab(h)
  return [L, Math.hypot(a, b), Math.atan2(b, a)]
}
const fromLch = (L, C, h) => hex([L, C * Math.cos(h), C * Math.sin(h)])
const L = (h) => oklab(h)[0]
const chroma = (h) => lch(h)[1]
/** OKLab: (1−t)·a + t·b. */
const mix = (a, b, t) => {
  const [p, q] = [oklab(a), oklab(b)]
  return hex(p.map((v, i) => (1 - t) * v + t * q[i]))
}
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x))

// --- composing the mode Doom does not have -----------------------------------

const NEUTRALS = ["bg", "bg-alt", "base0", "base1", "base2", "base3", "base4", "base5", "base6", "base7", "base8", "fg", "fg-alt"]
const HUES = ["red", "orange", "green", "teal", "yellow", "blue", "dark-blue", "magenta", "violet", "cyan", "dark-cyan"]
/** Doom's syntax classes -> the `code` role they carry. */
const SYNTAX = {
  comments: "comment",
  strings: "string",
  numbers: "number",
  constants: "constant",
  keywords: "keyword",
  operators: "operator",
  functions: "function",
  type: "type",
  variables: "variable",
}

/**
 * A theme's colours in the other mode. The neutrals keep hue and chroma (with a cap)
 * and their lightness is carried from the theme's bg→fg scale to the new mode's;
 * bg-alt, as in Doom, a little darker than bg in both modes. The named colours keep
 * hue and chroma, and their lightness moves towards that of Doom's themes in that
 * mode, keeping part of the difference between them.
 */
export function compose(S, towardLight) {
  const [Lb, Lf] = [L(S.bg), L(S.fg)]
  const [Lb2, Lf2, capBg, neutralCap] = towardLight ? [0.975, 0.3, 0.012, 0.03] : [0.235, 0.86, 0.02, 0.035]
  const k = (Lf2 - Lb2) / (Lf - Lb)
  const T = {}
  for (const v of NEUTRALS) {
    const [l, c, h] = lch(S[v])
    let l2 = v === "bg" ? Lb2 : Lb2 + (l - Lb) * k
    if (v === "bg-alt") l2 = Lb2 - Math.max(0.03, Math.abs(l - Lb) * Math.abs(k))
    T[v] = fromLch(clamp(l2, 0.08, 0.995), Math.min(c, v === "bg" || v === "bg-alt" ? capBg : neutralCap), h)
  }
  const hue = (x) => {
    const [l, c, h] = lch(x)
    const l2 = towardLight ? clamp(0.55 + 0.4 * (l - 0.75), 0.42, 0.66) : clamp(0.76 + 0.4 * (l - 0.55), 0.66, 0.86)
    return fromLch(l2, c, h)
  }
  for (const v of HUES) T[v] = hue(S[v])
  // The syntax classes: if they are one of the colours above (keywords is often
  // blue), its equivalent; if not (a blend), a hue like those above, or, if it has
  // almost no chroma (a grey comment), on the neutrals' scale.
  for (const v of Object.keys(SYNTAX)) {
    const equal = [...NEUTRALS, ...HUES].find((n) => S[n] === S[v])
    if (equal) T[v] = T[equal]
    else if (chroma(S[v]) >= 0.04) T[v] = hue(S[v])
    else {
      const [l, c, h] = lch(S[v])
      T[v] = fromLch(clamp(Lb2 + (l - Lb) * k, 0.08, 0.995), Math.min(c, neutralCap), h)
    }
  }
  return T
}

// --- the roles -----------------------------------------------------------------

const nearest = (S, names, goal) =>
  names.reduce((m, n) => (Math.abs(L(S[n]) - goal) < Math.abs(L(S[m]) - goal) ? n : m))

/**
 * The theme's orange (or magenta, if its orange is almost its red): the fill of the
 * control-plane nodes, and the accent of a palette without emphasis. It does not
 * follow the emphasis.
 */
const orange = (S) => (deltaE(S.orange, S.red) < 8 ? S.magenta : S.orange)

/**
 * The fixed roles (no adjustment) of a mode, from its theme's colours S. accent is
 * the default emphasis's text tone (below).
 */
function base(S, mode, galleryTitle, accent) {
  const light = mode === "light"
  const [Lb, Lf] = [L(S.bg), L(S.fg)]
  const panel = S["bg-alt"] === S.bg ? mix(S.bg, S.fg, 0.05) : S["bg-alt"]
  const muted = S[nearest(S, ["base5", "base4", "base6", "base3", "base7", "fg-alt"], Lb + 0.5 * (Lf - Lb))]
  const [, cy, hy] = lch(S.yellow)
  return {
    ui: {
      background: S.bg,
      panel,
      foreground: S.fg,
      muted,
      link: link(S.blue, S.bg, panel, mode),
      accent,
      mark: light ? `${fromLch(0.88, Math.min(cy, 0.1), hy)}88` : `${muted}66`,
    },
    gallery: { title: light ? galleryTitle : "{light.gallery.title}" },
  }
}

/**
 * The links (link): the theme's blue, moved only in OKLCH lightness (keeping its hue
 * and chroma, like the emphasis tones: moveL()) as little as possible until it
 * reaches TEXT_AA on background and on panel, because a link sits on the page and on
 * panels. It is text, and a reader does not choose another link colour by choosing a
 * palette: it is required of every palette, not only the default (2026-11-17). If it
 * already reaches it, as is.
 */
function link(blue, background, panel, mode) {
  const x = moveL(blue, background, on(TEXT_AA, background, panel))
  if (!x) throw new Error(`links, ${mode}: ${blue} does not reach ${TEXT_AA}:1 on ${background} and ${panel}`)
  return x
}

/**
 * The code blocks: each of the theme's syntax classes in its role, on the page's
 * background. Those that do not reach LEGIBLE on it (the comments of many dark
 * themes) move away from the background in lightness, keeping hue and chroma, until
 * they do.
 */
function code(S, mode) {
  const background = opaque(S.bg)
  const legible = (h) => {
    const [l, c, hh] = lch(h)
    const step = mode === "light" ? -0.005 : 0.005
    for (let k = 0; k <= 200; k++) {
      const x = k === 0 ? h : fromLch(clamp(l + k * step, 0, 1), c, hh)
      if (contrast(opaque(x), background) >= LEGIBLE) return x
    }
    throw new Error(`code, ${mode}: ${h} does not reach ${LEGIBLE}:1 on ${S.bg}`)
  }
  return {
    text: "{ui.foreground}",
    background: "{ui.background}",
    ...Object.fromEntries(Object.entries(SYNTAX).map(([v, role]) => [role, legible(S[v])])),
  }
}

/** The maps: zones and nodes from the background with a little of each hue, adjusted until distinguishable. */
function diagram(S, mode, _b) {
  const light = mode === "light"
  const s = light ? -1 : 1 // which way the zones move away from the background
  const [Lb, ab, bb] = oklab(S.bg)
  const hue = {
    "zone-blue": S.blue,
    "zone-green": S.green,
    "zone-amber": S.yellow,
    "zone-orange": S.orange,
    "zone-violet": deltaE(S.violet, S.blue) < 10 ? S.magenta : S.violet,
    "zone-grey": S.bg,
    "zone-brown": mix(S.red, S.orange, 0.5),
  }
  const t = Object.fromEntries(ZONES.map((z) => [z, z === "zone-grey" ? 0 : z === "zone-brown" ? 0.14 : 0.22]))
  const dL = Object.fromEntries(ZONES.map((z) => [z, z === "zone-brown" ? 0.06 : 0.04]))
  let ctrl = { t: 0.4, dL: light ? 0.075 : 0.1 }
  const nodes = light ? { node: 0.03, "node-soft": 0.012 } : { node: 0.13, "node-soft": 0.09 } // over the background
  // Where each hue pulls from the background, with a minimum chroma: a theme of muted
  // hues (spacegrey) would give zones indistinguishable from the grey.
  const strip = (h) => {
    const [, a, bq] = oklab(h)
    const n = Math.hypot(a - ab, bq - bb)
    const k = n > 0 && n < 0.12 ? 0.12 / n : 1
    return [ab + (a - ab) * k, bb + (bq - bb) * k]
  }
  const zone = (z) => {
    const [a, bq] = strip(hue[z])
    return hex([Lb + s * dL[z], (1 - t[z]) * ab + t[z] * a, (1 - t[z]) * bb + t[z] * bq])
  }
  const control = () => {
    const [, a, bq] = oklab(orange(S))
    return hex([Lb + (light ? -1 : 1) * ctrl.dL, (1 - ctrl.t) * ab + ctrl.t * a, (1 - ctrl.t) * bb + ctrl.t * bq])
  }
  const assemble = () => {
    const d = {}
    for (const [n, x] of Object.entries(nodes)) d[n] = hex([Math.min(1, Lb + x), ab * 0.6, bb * 0.6])
    d["node-control"] = control()
    for (const z of ZONES) d[z] = zone(z)
    return d
  }
  for (let round = 0; ; round++) {
    const d = assemble()
    const bad = distances(d)
    if (bad.length === 0) return d
    if (round > 400) throw new Error(`maps, ${mode}: not distinguishable after adjusting: ${bad.map((m) => m.join("/")).join(", ")}`)
    for (const [x, y] of bad) {
      if (ZONES.includes(x)) {
        // Two zones: more hue, and one a little further from the background (two
        // almost equal hues only separate this way).
        // Next to the grey one, the other also moves in lightness: near white, sRGB
        // leaves no chroma.
        for (const z of [x, y]) if (z !== "zone-grey") t[z] = Math.min(0.7, t[z] + 0.015)
        const other = x === "zone-grey" ? y : y === "zone-grey" ? x : y
        dL[other] = Math.min(0.12, dL[other] + 0.002)
      } else if (x === "node-control") {
        ctrl = { t: Math.min(0.8, ctrl.t + 0.02), dL: Math.min(0.15, ctrl.dL + 0.003) }
      } else if (light) {
        dL[y] = Math.min(0.12, dL[y] + 0.004) // the zone darker than the paper; the node lighter
      } else if (dL[y] > 0.015) {
        dL[y] = Math.max(0.015, dL[y] - 0.003) // the node lighter than the zone
      } else {
        nodes[x] = Math.min(0.2, nodes[x] + 0.005)
      }
    }
  }
}

/** The map pairs below their distance (with a margin): [node|zone, zone]. */
export function distances(d, nodeSep = SEP_NODE, sepZone = SEP_ZONE) {
  const bad = []
  for (const n of NODES) for (const z of ZONES) if (deltaE(d[n], d[z]) < nodeSep) bad.push([n, z])
  for (const [i, a] of ZONES.entries())
    for (const z of ZONES.slice(i + 1))
      if (deltaE(d[a], d[z]) < sepZone && `${a}/${z}` !== "zone-amber/zone-orange") bad.push([a, z])
  return bad
}

/**
 * Each candidate brought into the graph's band: its lightness inside it and, if it
 * does not separate from ink, in steps of 0.02 towards the side of the band furthest
 * from ink.
 */
function inBand(mode, ink) {
  const [lo, hi] = BAND[mode]
  const far = L(ink) < (lo + hi) / 2 ? hi - 0.03 : lo + 0.03
  return (h) => {
    const [l, c, hh] = lch(h)
    const l0 = clamp(l, lo + 0.03, hi - 0.03)
    const steps = Math.ceil(Math.abs(far - l0) / 0.02)
    return Array.from({ length: steps + 1 }, (_, k) =>
      fromLch(l0 + (steps ? (k / steps) * (far - l0) : 0), Math.max(c, GRAPH_CHROMA + 0.02), hh),
    )
  }
}

/** What the graph's band asks of accent and neighbour (test/contrast.test.ts's, with a margin). */
const inTheBand = (mode, ink) => (h) => {
  const [lo, hi] = BAND[mode]
  return chroma(h) >= GRAPH_CHROMA + 0.005 && L(h) >= lo && L(h) <= hi && deltaE(h, ink) >= SEP_GRAPH
}

/**
 * neighbour: the first of blue, cyan, teal, violet, dark-cyan and green that, brought
 * into the band, meets the chroma and the distance to ink. It does not depend on the
 * emphasis: the emphasis is chosen far from it, so changing emphasis does not change
 * the neighbour.
 */
export function neighbour(S, mode, ink) {
  const vale = inTheBand(mode, ink)
  const carry = inBand(mode, ink)
  for (const n of ["blue", "cyan", "teal", "violet", "dark-cyan", "green"]) {
    const x = carry(S[n]).find(vale)
    if (x) return x
  }
  throw new Error(`graph, ${mode}: no neighbour meets chroma, band and distance to ink`)
}

/** The accent of a palette without emphasis: the first of its warm hues that fits the band. */
export function withoutEmphasis(S, mode, { ink, neighbour }) {
  const vale = inTheBand(mode, ink)
  const carry = inBand(mode, ink)
  for (const c of [orange(S), S.orange, S.red, S.magenta, S.yellow, S.green]) {
    const x = carry(c).find((h) => vale(h) && deltaE(h, neighbour) >= SEP_GRAPH)
    if (x) return x
  }
  throw new Error(`graph, ${mode}: no accent meets chroma, band and distances`)
}

/** The graph: accent is the default emphasis's graphic tone; neighbour, the neighbour. */
export function graph(S, mode, b, accent, neighbour) {
  const light = mode === "light"
  const [Lb, ab, bb] = oklab(S.bg)
  return {
    ink: "{ui.foreground}",
    accent,
    neighbour,
    visited: light ? hex([Lb - 0.09, ab, bb]) : "{ui.panel}",
    edge: mix(b.ui.muted, S.bg, 0.3),

  }
}

// --- emphasis --------------------------------------------------------------------
//
// A palette's emphasis swatches: the named colours of its Doom theme that are not
// already used for something they could be confused with. The reader chooses one
// (data-emphasis on <html>), and with it change ui.accent (emphasised text, and by
// reference the diagrams' highlight) and the graph's accent (and with it, in
// chord-graph, the "You are here" marker and its focus ring). Unchanged: the links,
// the danger red (the diagrams' blocked), the code, and the graph's neighbour.
//
// Each swatch carries, in each mode, two tones of the same colour: the text one
// (4.5:1 on background and on panel) and the graphic one (3:1 on both, and inside the
// graph's lightness and chroma band, because it is its accent). Each tone is the Doom
// colour moved only in OKLCH lightness (L), keeping its hue (h) and chroma (C), as
// little as possible until it passes; if sRGB has no such chroma at that lightness,
// the chroma is clipped, not the hue (hex()). In the mode Doom does not provide, the
// starting colour is the composed one (compose()).
//
// A swatch is offered only if it passes in both modes, because data-emphasis does not
// depend on the mode:
// - both tones at ΔE00 >= SEP_WARNING from the danger red and from the links;
// - both tones at ΔE00 >= SEP_GRAPH00 from the graph's ink and neighbour;
// - the graphic one inside the graph's band and at OKLab ΔE >= SEP_GRAPH from ink and
//   neighbour (what test/contrast.test.ts requires of the accent);
// - and at ΔE00 >= SEP_SWATCHES from the others offered, in its graphic and text
//   tones and in both modes, so as not to offer two near-identical ones (separate(),
//   below).

/** The Doom colours that can be emphasis, in the order offered, with their (display) names. */
export const EMPHASIS = {
  red: "red",
  orange: "orange",
  yellow: "yellow",
  green: "green",
  teal: "green azulado",
  cyan: "cyan",
  blue: "blue",
  violet: "violet",
  magenta: "magenta",
}
export const TEXT_AA = 4.5
export const GRAPHIC = 3
export const SEP_WARNING = 12
export const SEP_GRAPH00 = 16
/**
 * The minimum distance between two of a palette's swatches (separate()): ΔE00 between
 * their graphic tones and between their text tones, in both modes. Around ΔE00 10, two
 * interface colours look different at a glance; but that is on large surfaces, and
 * here the graphic tone is seen in a small circle in the menu and the text tone in thin
 * type, where the same difference is perceived less. Hence a margin over 10: 12, the
 * distance this program already uses so that the emphasis is not confused with the
 * danger red or the links (SEP_WARNING). Measured on 2026-11-17 among those that pass
 * everything else: below 10, gruvbox's violet and magenta (4.7 in text; 12.3 in the
 * graphic tone) and xcode's (8.5), the twins the owner saw, and seven more pairs;
 * between 10 and 12, ayu's orange and yellow (10.6) and one's (11.6), which go; from 12
 * to 15 remain challenger-deep's violet and magenta (12.3), spacegrey's (14.1) and
 * bluloco's (14.8), which differ in OKLCH hue by 24°, 14° (with more than twice the
 * chroma) and 38° (the twins have the same hue, at 3° or 10°), and four orange, yellow
 * and green pairs (12.3 to 13.2); 15 would remove those too.
 */
export const SEP_SWATCHES = 12
/** The tones of a swatch measured between swatches: the visible ones (the graph's comes from the graphic one). */
export const SEPARATED_HUES = ["graphic", "text"]
/**
 * The OKLCH hue band of blue (as in the 2026-11-16 audit): links are blue in almost
 * every theme, and the default emphasis avoids them.
 */
export const BLUE = [200, 275]
/** And, even if a theme's links are not blue, this distance from their hue (degrees). */
export const NEAR_LINK = 30
/** OKLCH lightness step when searching for a tone. */
const STEP_L = 0.0025

/** OKLCH hue in degrees, 0..360. */
export const hueH = (h) => ((lch(h)[2] * 180) / Math.PI + 360) % 360
const distanceH = (a, b) => Math.min(Math.abs(a - b), 360 - Math.abs(a - b))

/**
 * h's tone, moved only in L (keeping its C and h), as little as possible until it
 * meets `ok`; at equal distance, first towards the side away from the background.
 * undefined if none does.
 */
export function moveL(h, background, ok) {
  const [l, c, hh] = lch(h)
  const far = L(background) > 0.5 ? -1 : 1
  for (let k = 0; k * STEP_L <= 1; k++)
    for (const s of k === 0 ? [0] : [far, -far]) {
      const l2 = l + s * k * STEP_L
      if (l2 < 0 || l2 > 1) continue
      const x = fromLch(l2, c, hh)
      if (ok(x)) return x
    }
  return undefined
}

const on = (min, ...backgrounds) => (x) => backgrounds.every((f) => contrast(opaque(x), opaque(f)) >= min)

/**
 * A palette's swatches. `modes[m]` brings, for each mode, its theme's colours (S) and
 * the roles it is measured against: background, panel, link, danger (the red), ink and
 * neighbour. Returns those that pass (the candidates; those separate() leaves are
 * offered), in EMPHASIS's order:
 * { id, name, light: { graphic, text }, dark: { graphic, text } }.
 * `previous`: those that go first (a hand-written palette's default); they come first,
 * as they are, and the others are also measured against them.
 */
export function swatches(modes, previous = []) {
  const outside = [...previous]
  for (const id of Object.keys(EMPHASIS)) {
    if (previous.some((o) => o.id === id)) continue
    const m = { id, name: EMPHASIS[id] }
    let vale = true
    for (const mode of MODES) {
      const { S, background, panel, link, danger, ink, neighbour } = modes[mode]
      const far = (x) =>
        [danger, link].every((y) => deltaE00(x, y) >= SEP_WARNING) &&
        [ink, neighbour].every((y) => deltaE00(x, y) >= SEP_GRAPH00)
      const text = moveL(S[id], background, on(TEXT_AA, background, panel))
      const graphic = moveL(S[id], background, on(GRAPHIC, background, panel))
      const band = inTheBand(mode, ink)
      const graph =
        graphic &&
        inBand(mode, ink)(graphic).find(
          (x) => band(x) && deltaE(x, neighbour) >= SEP_GRAPH && on(GRAPHIC, background, panel)(x),
        )
      if (![text, graphic, graph].every((x) => x && far(x))) {
        vale = false
        break
      }
      m[mode] = { graphic, text, graph }
    }
    if (vale) outside.push(m)
  }
  return outside
}

/** What separates two swatches: the smallest ΔE00 between their SEPARATED_HUES tones, in both modes. */
export const swatchDistance = (a, b) =>
  Math.min(...MODES.flatMap((mode) => SEPARATED_HUES.map((t) => deltaE00(a[mode][t], b[mode][t]))))

/**
 * The swatches offered: of `ms`, those that remain at swatchDistance >= `sep` from
 * each other. While some pair is closer, the closest is taken and one of the two
 * removed: never the default (`pred`, its id); if neither is, the one closer to the
 * others remaining (its smallest distance to them, not counting the other of the
 * pair), so the one most different from the rest stays. Ties go by EMPHASIS's order (an
 * id not in it, a hand-written palette's default, goes first): at equal distance, the
 * pair whose first goes first, and failing that whose second; at equal closeness to
 * the rest, the later one is removed. So it does not depend on `ms`'s order, only on
 * its swatches, `pred` and `sep`. Fails if `pred` is not one of `ms` (unless there are
 * none): without it, nothing would protect it. Returns those remaining in `ms`'s order.
 * `distance`: the distance between two swatches (the tests pass a table).
 */
export function separate(ms, pred, sep = SEP_SWATCHES, distance = swatchDistance) {
  if (ms.length > 0 && !ms.some((m) => m.id === pred)) throw new Error(`separate: the default (${pred}) is not among the swatches`)
  const place = (m) => Object.keys(EMPHASIS).indexOf(m.id)
  let remain = [...ms].sort((x, y) => place(x) - place(y))
  const d = new Map()
  const dist = (a, b) => {
    const k = `${a.id}/${b.id}`
    if (!d.has(k)) d.set(k, distance(a, b))
    return d.get(k)
  }
  for (;;) {
    // With `remain` in EMPHASIS's order, the first pair at the smallest distance is the tie-break's.
    let par
    for (const [i, a] of remain.entries())
      for (const b of remain.slice(i + 1))
        if (dist(a, b) < sep && (!par || dist(a, b) < par.d)) par = { a, b, d: dist(a, b) }
    if (!par) return ms.filter((m) => remain.includes(m))
    const { a, b } = par
    const toRest = (x, other) =>
      Math.min(Infinity, ...remain.filter((y) => y !== x && y !== other).map((y) => dist(x, y)))
    const outside = a.id === pred ? b : b.id === pred ? a : toRest(a, b) < toRest(b, a) ? a : b
    remain = remain.filter((x) => x !== outside)
  }
}

/** Whether a swatch falls in the blues or near the links' hue, in some mode. */
export function asLink(m, modes) {
  return MODES.some((mode) => {
    const h = hueH(m[mode].graphic)
    return (h >= BLUE[0] && h <= BLUE[1]) || distanceH(h, hueH(modes[mode].link)) < NEAR_LINK
  })
}

/** Mean OKLCH chroma of the graphic tone in both modes, to three decimals. */
export const midChroma = (m) => Math.round(((chroma(m.light.graphic) + chroma(m.dark.graphic)) / 2) * 1000) / 1000

/**
 * The default emphasis, the palette's "signature": the swatch with the most chroma
 * (midChroma) among those that are not like the links (asLink); if all are, the
 * one with the most chroma of all. At equal chroma, the first in EMPHASIS's order. It
 * does not depend on `ms`'s order. Without swatches, undefined. `modes[m].link`: the
 * links.
 */
export function defaultId(ms, modes) {
  const far = ms.filter((m) => !asLink(m, modes))
  const order = Object.keys(EMPHASIS)
  return [...(far.length ? far : ms)].sort(
    (a, b) => midChroma(b) - midChroma(a) || order.indexOf(a.id) - order.indexOf(b.id),
  )[0]
}

/** A palette's two modes, from data/doom.json. */
export function palette(data, name) {
  const p = data.palettes[name]
  const native = (m) => p[m] && data.themes[p[m]]
  for (const m of MODES)
    if (native(m) && (L(data.themes[p[m]].bg) > 0.5) !== (m === "light"))
      throw new Error(`${name}: ${p[m]} is not a ${m} theme`)
  if (!native("light") && !native("dark")) throw new Error(`${name}: no theme`)
  const S = {
    dark: native("dark") ?? compose(data.themes[p.light], false),
    light: native("light") ?? compose(data.themes[p.dark], true),
  }
  // First what does not depend on the emphasis (accent, not yet set); then the
  // swatches, measured against it; and with the default, accent and the graph's accent.
  const b0 = {}
  const against = {}
  for (const m of MODES) {
    b0[m] = base(S[m], m, S.dark.fg, undefined)
    const ink = b0[m].ui.foreground
    against[m] = {
      S: S[m],
      background: b0[m].ui.background,
      panel: b0[m].ui.panel,
      link: b0[m].ui.link,
      danger: S[m].red,
      ink,
      neighbour: neighbour(S[m], m, ink),
    }
  }
  const candidates = swatches(against)
  // With no swatch at all (nova: with its half-lit background, no tone inside the
  // graph's band reaches 3:1), the palette stays as it was: ui.accent, the theme's
  // orange; the graph's accent, the first that fits the band; highlight, ui.accent.
  // The default comes from all that pass, before separating, and separate() does not remove it.
  const pred = defaultId(candidates, against)
  const ms = separate(candidates, pred?.id)
  const modes = {}
  for (const m of MODES) {
    const b = base(S[m], m, S.dark.fg, pred ? pred[m].text : orange(S[m]))
    const d = diagram(S[m], m, b)
    modes[m] = {
      ...b,
      diagram: {
        ink: "{ui.foreground}",
        background: "{ui.background}",
        border: "{ui.foreground}",
        node: d.node,
        "node-soft": d["node-soft"],
        "node-control": d["node-control"],
        line: b.ui.muted,
        outline: mix(b.ui.muted, S[m].bg, 0.35),
        highlight: pred ? pred[m].graphic : "{ui.accent}",
        blocked: S[m].red,

        ...Object.fromEntries(ZONES.map((z) => [z, d[z]])),
      },
      graph: graph(S[m], m, b, pred ? pred[m].graph : withoutEmphasis(S[m], m, against[m]), against[m].neighbour),
      code: code(S[m], m),
    }
  }
  return { origin: p, modes, emphasis: pred ? { defaultId: pred.id, swatches: ms } : undefined, candidates }
}

// --- the emphasis of the hand-written palettes ------------------------------------
//
// gruvbox and monokai (owner, 2026-11-16) are written by hand, but take their emphasis
// swatches from the Doom themes «emphasisOnly» names in data/doom.json (doom-gruvbox and
// doom-gruvbox-light; doom-monokai-classic, Doom's theme with our monokai's colours).
// Their default does not come from the rule: it is the usual one, ui.accent,
// diagram.highlight and graph.accent as they are in their YAML, so the palette without
// data-emphasis does not change. It goes first, named after the Doom colour that is its
// graphic tone in each mode Doom provides (gruvbox and monokai: orange), or
// «defaultId» if it is none. The others, Doom's, by the same rules as the Doom
// palettes', measured against the YAML's roles.

/** The tones of a hand-written palette's default: its usual ones. */
const huesOf = (v) => ({ graphic: v.diagram.highlight, text: v.ui.accent, graph: v.graph.accent })

/** The marker of the generated emphasis block at the end of a hand-written palette's YAML. */
export const EMPHASIS_MARK = "# Emphasis swatches generated by scripts/from-doom.mjs"

/** The hand-written part of the YAML: everything before the generated block. */
export function partByHand(text) {
  const i = text.indexOf(`\n${EMPHASIS_MARK}`)
  return i < 0 ? text : text.slice(0, i)
}

/**
 * A hand-written palette's candidates, from the Doom themes of
 * `data.emphasisOnly[name]`, before separate(): { pred, candidates }, with the default
 * first. `p`: the resolved palette (src/tokens.ts), without its emphasis block.
 */
export function candidatesByHand(data, name, p) {
  const o = data.emphasisOnly?.[name]
  if (!o) throw new Error(`${name}: not in emphasisOnly`)
  const native = (m) => o[m] && data.themes[o[m]]
  if (!native("light") && !native("dark")) throw new Error(`${name}: no theme`)
  const S = {
    dark: native("dark") ?? compose(data.themes[o.light], false),
    light: native("light") ?? compose(data.themes[o.dark], true),
  }
  const against = Object.fromEntries(
    MODES.map((m) => {
      const v = p[m]
      const r = { background: v.ui.background, panel: v.ui.panel, link: v.ui.link }
      return [m, { S: S[m], ...r, danger: v.diagram.blocked, ink: v.graph.ink, neighbour: v.graph.neighbour }]
    }),
  )
  const hues = Object.fromEntries(MODES.map((m) => [m, huesOf(p[m])]))
  const id = Object.keys(EMPHASIS).find((c) => MODES.every((m) => !native(m) || S[m][c] === hues[m].graphic))
  const pred = { id: id ?? "defaultId", name: id ? EMPHASIS[id] : "defaultId", ...hues }
  return { pred, candidates: swatches(against, [pred]) }
}

/** The swatches a hand-written palette offers: { defaultId, swatches }, with the default first. */
export function emphasisByHand(data, name, p) {
  const { pred, candidates } = candidatesByHand(data, name, p)
  return { defaultId: pred.id, swatches: separate(candidates, pred.id) }
}

/** The emphasis block at the end of a hand-written palette's YAML. */
export function blockByHand(data, name, p) {
  const { commit } = data.provenance
  const themes = Object.entries(data.emphasisOnly[name]).map(([m, t]) => `${m}, ${t}`).join("; ")
  return [
    `${EMPHASIS_MARK} from data/doom.json:`,
    "# not edited by hand; regenerate with `npm run doom`. The colours, from Doom Emacs",
    `# (https://github.com/doomemacs/themes, MIT, commit ${commit.slice(0, 12)}), its themes:`,
    `# ${themes}.`,
    "# The default, the first, is ui.accent, diagram.highlight and graph.accent from",
    "# above, as they are; the others, like the Doom palettes' (README, \"Emphasis\").",
    ...emphasisLines(emphasisByHand(data, name, p)),
  ].join("\n") + "\n"
}

/**
 * The hand-written palettes with Doom swatches: name → the whole text of its YAML (the
 * hand-written part, as is, and the block). `read(name)`: the current text;
 * `resolver(name, text)`: the resolved palette (resolveText from src/tokens.ts).
 */
export function generateByHand(data, read, resolver) {
  return new Map(
    Object.keys(data.emphasisOnly ?? {})
      .sort()
      .map((n) => {
        const hand = partByHand(read(n))
        try {
          return [n, `${hand}\n${blockByHand(data, n, resolver(n, hand))}`]
        } catch (e) {
          throw new Error(`${n}: ${e.message}`)
        }
      }),
  )
}

// --- YAML ----------------------------------------------------------------------

/** The `emphasis:` lines of a palette YAML. */
function emphasisLines(emphasis) {
  const lines = ["emphasis:", `  defaultId: ${emphasis.defaultId}`, "  swatches:"]
  for (const m of emphasis.swatches) {
    lines.push(`    - id: ${m.id}`, `      name: ${m.name}`)
    for (const mode of MODES) lines.push(
        `      ${mode}: { graphic: "${m[mode].graphic}", text: "${m[mode].text}", graph: "${m[mode].graph}" }`,
      )
  }
  return lines
}

function yaml(data, name, { origin, modes, emphasis }) {
  const { commit } = data.provenance
  const mode = (m) =>
    origin[m]
      ? `${origin[m]}, as is`
      : `composed from ${origin[m === "light" ? "dark" : "light"]}: the same hues, ${
          m === "light" ? "darker, on a near-white paper" : "lighter, on a dark paper"
        }`
  const lines = [
    "# SPDX-License-Identifier: GPL-3.0-or-later",
    `# Palette ${name}, for readers who choose it: the colours of the Doom Emacs`,
    `# themes (https://github.com/doomemacs/themes, MIT, commit ${commit.slice(0, 12)}; the`,
    "# licence and provenance are in data/PROVENANCE).",
    `# - light: ${mode("light")}.`,
    `# - dark: ${mode("dark")}.`,
    "# Not the default: AA contrasts are not required of it (owner, 2026-11-13),",
    "# except the links' (2026-11-17); what makes the site work is.",
    "#",
    `${MARK} from data/doom.json: not edited by hand;`,
    "# change the program or the data and regenerate with `npm run doom`.",
    "isDefault: false",
  ]
  for (const m of MODES) {
    lines.push("", `${m}:`)
    for (const [g, roles] of Object.entries(modes[m])) {
      lines.push(`  ${g}:`)
      for (const [p, v] of Object.entries(roles)) lines.push(`    ${p}: "${v}"`)
    }
  }
  if (!emphasis) return lines.join("\n") + "\n"
  lines.push(
    "",
    "# The emphasis swatches (scripts/doom.mjs): the default gives ui.accent (its text",
    "# tone), diagram.highlight (the graphic one) and graph.accent (the graph's).",
    ...emphasisLines(emphasis),
  )
  return lines.join("\n") + "\n"
}

/** Each Doom palette: name → YAML text. */
export function generate(data) {
  return new Map(
    Object.keys(data.palettes)
      .sort()
      .map((n) => {
        try {
          return [n, yaml(data, n, palette(data, n))]
        } catch (e) {
          throw new Error(`${n}: ${e.message}`)
        }
      }),
  )
}

