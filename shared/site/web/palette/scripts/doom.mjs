const SEP_NODE = 3.3
const SEP_ZONE = 2.3
const SEP_GRAPH = 16
const BAND = { light: [0.43, 0.77], dark: [0.48, 0.67] }
const GRAPH_CHROMA = 0.1
// The least a code role reaches on its background: legible, if not AA (it is not the
