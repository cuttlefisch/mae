// The Doom Emacs palettes: from data/doom.json (each theme's colours, extracted by
// scripts/extract-doom.mjs) to the text of palettes/<name>.yaml. scripts/from-doom.mjs
// writes them (npm run doom); test/doom.test.ts requires palettes/ to be what comes
// out of here. The YAML files are not edited by hand: change this program or the
// data, and regenerate.
//
// Doom gives each theme in a single mode. If the theme has a sibling (doom-one and
// doom-one-light), each mode comes from its own; if not, the missing one is composed
// from the same theme's colours: the same hues, darker on a near-white paper for
// light, or lighter on a dark paper for dark.
//
// From Doom's variables to the roles:
// - background and panel: bg and bg-alt; foreground: fg; muted: the base (or fg-alt)
//   at mid-lightness between bg and fg, like comments;
// - link: blue, moved only in OKLCH lightness (link(), below) if it does not reach
//   4.5:1 on background and panel; accent: the text tone of the default emphasis
//   (below, "emphasis");
// - maps: zones and nodes, the background with a little of each hue (OKLab), with
//   lightness and amount of hue adjusted until they are distinguishable (the
//   distances of test/contrast.test.ts, with a margin);
// - maps: highlight, the default emphasis's graphic tone; blocked, the theme's red;
// - graph: neighbour, blue (or the first that works), brought to the lightness and
//   chroma of its band; accent, the default emphasis's graph tone.
// - code: text and background, the page's; each role, Doom's matching syntax class
//   (comments, strings, numbers, constants, keywords, operators, functions, type,
//   variables), moved away from the background just enough to reach 3:1 if it does
//   not.
// AA contrasts are not sought: these are not the default palette (owner,
// 2026-11-13), except the links', required of every palette (2026-11-17). What makes
// the site work is, and if a theme cannot reach it, the program fails with the reason
// instead of writing it.
