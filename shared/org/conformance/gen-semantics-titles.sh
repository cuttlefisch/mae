#!/bin/sh
# Regenerate semantics-titles.tsv, the Emacs oracle for the titles and
# levels of semantics() nodes (tests/semantics_differential.rs, ADR-112 D5).
# Checked in so CI needs no Emacs; run this when a corpus file or a
# tests/semantics/ fixture changes, and review the diff like code.
#
# Usage (from anywhere):  shared/org/conformance/gen-semantics-titles.sh
#
# Requires: emacs (batch) and git. The corpus is every .org file under
# assets/ and tests/ that git does not ignore (the differential's bundled
# corpus, tests/support/mod.rs) plus the tests/semantics/ fixtures. POSIX sh
# (principle #13).
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
out="$here/semantics-titles.tsv"

command -v emacs >/dev/null 2>&1 || { echo "gen-semantics-titles.sh: emacs not found" >&2; exit 1; }

manifest=$(mktemp "${TMPDIR:-/tmp}/mae-org-titles.XXXXXX")
body=$(mktemp "${TMPDIR:-/tmp}/mae-org-titles-out.XXXXXX")
trap 'rm -f "$manifest" "$body"' EXIT INT TERM

(cd "$root" && git ls-files --cached --others --exclude-standard -- 'assets/*.org' 'tests/*.org' 'shared/org/tests/semantics/*.org') |
    sort | while IFS= read -r rel; do
        printf '%s\t%s\n' "$root/$rel" "$rel"
    done > "$manifest"

emacs -Q --batch -l "$here/semantics-titles.el" --manifest "$manifest" > "$body"
version=$(emacs -Q --batch --eval '(progn (require (quote org)) (princ org-version))')
{
    printf '# Generated by gen-semantics-titles.sh with Org %s; do not edit by hand.\n' "$version"
    printf '# FILE\tID\tLINE\tLEVEL\tTITLE\n'
    cat "$body"
} > "$out"
echo "gen-semantics-titles.sh: $(grep -vc '^#' "$out") nodes written with Org $version"
